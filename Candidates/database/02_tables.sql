/*
  Bank details (req 3.1.3 "bank details (encrypted)"). Kept in their own table so access can be restricted separately.
  Encrypted by the application (AES-256-GCM) before it reaches the database; SQL Server stores only IV + ciphertext.
  AccountLast4 is the only plaintext, for display.
*/
IF OBJECT_ID(N'candidates.CandidateBankDetail', N'U') IS NULL
CREATE TABLE candidates.CandidateBankDetail (
    CandidateId       UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_CandidateBankDetail PRIMARY KEY
                                       CONSTRAINT FK_CandidateBankDetail_Candidate REFERENCES candidates.Candidate (CandidateId) ON DELETE CASCADE,
    EncryptionIv      VARBINARY(16)    NOT NULL,
    Ciphertext        VARBINARY(MAX)   NOT NULL,
    KeyVersion        SMALLINT         NOT NULL CONSTRAINT DF_CandidateBankDetail_KeyVersion DEFAULT (1),  -- supports key rotation
    AccountLast4      CHAR(4)          NOT NULL CONSTRAINT CK_CandidateBankDetail_Last4 CHECK (AccountLast4 NOT LIKE '%[^0-9]%'),
    UpdatedAt         DATETIME2(3)     NOT NULL CONSTRAINT DF_CandidateBankDetail_UpdatedAt DEFAULT (SYSUTCDATETIME())
);
GO

/* ======================= Audit log (req 3.10.2, NFR audit logging) ======================= */
-- No FK to Candidate: audit rows must outlive merges and erasures.
IF OBJECT_ID(N'candidates.AuditLog', N'U') IS NULL
CREATE TABLE candidates.AuditLog (
    AuditId           BIGINT           IDENTITY(1, 1) NOT NULL CONSTRAINT PK_AuditLog PRIMARY KEY,
    OccurredAt        DATETIME2(3)     NOT NULL CONSTRAINT DF_AuditLog_OccurredAt DEFAULT (SYSUTCDATETIME()),
    UserName          NVARCHAR(150)    NOT NULL,
    Action            NVARCHAR(100)    NOT NULL,
    CandidateId       UNIQUEIDENTIFIER NULL,
    Details           NVARCHAR(1000)   NULL
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_AuditLog_Candidate' AND object_id = OBJECT_ID(N'candidates.AuditLog'))
    CREATE INDEX IX_AuditLog_Candidate ON candidates.AuditLog (CandidateId, OccurredAt) WHERE CandidateId IS NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_AuditLog_OccurredAt' AND object_id = OBJECT_ID(N'candidates.AuditLog'))
    CREATE INDEX IX_AuditLog_OccurredAt ON candidates.AuditLog (OccurredAt);
GO

/* ======================= Data classification (Privacy Act PII) ======================= */
ADD SENSITIVITY CLASSIFICATION TO
    candidates.Candidate.FirstName, candidates.Candidate.LastName
    WITH (LABEL = 'Confidential - Personal', INFORMATION_TYPE = 'Name', RANK = MEDIUM);
ADD SENSITIVITY CLASSIFICATION TO
    candidates.Candidate.Email, candidates.Candidate.Phone, candidates.Candidate.Location,
    candidates.CandidateReference.Email, candidates.CandidateReference.Phone
    WITH (LABEL = 'Confidential - Personal', INFORMATION_TYPE = 'Contact Info', RANK = MEDIUM);
ADD SENSITIVITY CLASSIFICATION TO
    candidates.Candidate.VisaType, candidates.Candidate.VisaExpiry, candidates.Candidate.ClearanceLevel
    WITH (LABEL = 'Confidential - Personal', INFORMATION_TYPE = 'National ID', RANK = HIGH);
ADD SENSITIVITY CLASSIFICATION TO
    candidates.Candidate.Abn, candidates.CandidateOnboarding.SuperMemberNumber,
    candidates.CandidateBankDetail.Ciphertext, candidates.CandidateBankDetail.AccountLast4
    WITH (LABEL = 'Highly Confidential', INFORMATION_TYPE = 'Financial', RANK = HIGH);
GO
