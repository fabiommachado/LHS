IF OBJECT_ID(N'candidates.Candidate', N'U') IS NULL
CREATE TABLE candidates.Candidate (
    CandidateId              UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_Candidate_Id DEFAULT (NEWSEQUENTIALID()),
    StatusCode               NVARCHAR(20)     NOT NULL CONSTRAINT DF_Candidate_Status DEFAULT (N'Prospect')
                                              CONSTRAINT FK_Candidate_Status REFERENCES candidates.CandidateStatus (StatusCode),

    -- Personal & contact (req 3.1.1)
    FirstName                NVARCHAR(100)    NULL,
    LastName                 NVARCHAR(100)    NULL,
    Email                    NVARCHAR(254)    NULL,
    Phone                    NVARCHAR(30)     NULL,
    Location                 NVARCHAR(120)    NULL,
    CurrentEmployer          NVARCHAR(150)    NULL,
    CurrentTitle             NVARCHAR(150)    NULL,
    Abn                      CHAR(11)         NULL,
    AvailabilityDate         DATE             NULL,
    SalaryBasis              NVARCHAR(20)     NOT NULL CONSTRAINT DF_Candidate_SalaryBasis DEFAULT (N'Daily rate'),
    SalaryAmount             DECIMAL(12, 2)   NULL,

    -- Security clearance (req 3.1.1 / 3.1.2)
    ClearanceLevel           NVARCHAR(10)     NOT NULL CONSTRAINT DF_Candidate_ClearanceLevel DEFAULT (N'None'),
    ClearanceExpiry          DATE             NULL,
    ClearanceIssuingAgency   NVARCHAR(100)    NULL,
    ClearanceVerification    NVARCHAR(12)     NOT NULL CONSTRAINT DF_Candidate_ClearanceVerification DEFAULT (N'Unverified'),

    -- Right to work (req 3.1.2)
    WorkRights               NVARCHAR(30)     NULL,
    VisaType                 NVARCHAR(60)     NULL,
    VisaExpiry               DATE             NULL,
    VisaRestrictions         NVARCHAR(200)    NULL,

    -- Sourcing & LinkedIn (req 3.1.1)
    SourceChannelCode        NVARCHAR(30)     NULL CONSTRAINT FK_Candidate_SourceChannel REFERENCES candidates.SourceChannel (SourceChannelCode),
    SourceDetail             NVARCHAR(200)    NULL,
    LinkedInUrl              NVARCHAR(300)    NULL,
    LinkedInOutreachStatus   NVARCHAR(20)     NOT NULL CONSTRAINT DF_Candidate_Outreach DEFAULT (N'Not contacted'),

    -- Privacy Act consent (req 3.1.1 / 2.10)
    ConsentGiven             BIT              NOT NULL CONSTRAINT DF_Candidate_ConsentGiven DEFAULT (0),
    ConsentDate              DATE             NULL,
    ConsentMethod            NVARCHAR(30)     NULL,
    CollectionNoticeProvided BIT              NOT NULL CONSTRAINT DF_Candidate_CollectionNotice DEFAULT (0),

    Notes                    NVARCHAR(MAX)    NULL,   -- internal only; never exposed to the candidate portal

    -- Privacy erasure tombstone & merge trail (req 3.10.2 / 3.1.1)
    IsErased                 BIT              NOT NULL CONSTRAINT DF_Candidate_IsErased DEFAULT (0),
    ErasedAt                 DATETIME2(3)     NULL,
    ErasureReason            NVARCHAR(500)    NULL,

    CreatedAt                DATETIME2(3)     NOT NULL CONSTRAINT DF_Candidate_CreatedAt DEFAULT (SYSUTCDATETIME()),
    UpdatedAt                DATETIME2(3)     NOT NULL CONSTRAINT DF_Candidate_UpdatedAt DEFAULT (SYSUTCDATETIME()),  -- "last activity" for 7-year retention
    RowVer                   ROWVERSION       NOT NULL,  -- optimistic concurrency for the API

    -- Normalised match keys for duplicate detection (same rules as domain.js).
    EmailKey    AS (LOWER(LTRIM(RTRIM(Email)))) PERSISTED,
    PhoneKey    AS (CASE WHEN LEN(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(Phone, N' ', N''), N'-', N''), N'(', N''), N')', N''), N'+', N'')) >= 9
                         THEN RIGHT(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(Phone, N' ', N''), N'-', N''), N'(', N''), N')', N''), N'+', N''), 9) END) PERSISTED,
    LinkedInKey AS (CAST(LOWER(TRIM(N'/ ' FROM REPLACE(REPLACE(REPLACE(LinkedInUrl, N'https://', N''), N'http://', N''), N'www.', N''))) AS NVARCHAR(300))) PERSISTED,

    CONSTRAINT PK_Candidate PRIMARY KEY CLUSTERED (CandidateId),
    CONSTRAINT CK_Candidate_Name            CHECK (IsErased = 1 OR (FirstName IS NOT NULL AND LastName IS NOT NULL)),
    CONSTRAINT CK_Candidate_Contact         CHECK (IsErased = 1 OR Email IS NOT NULL OR Phone IS NOT NULL OR LinkedInUrl IS NOT NULL),
    CONSTRAINT CK_Candidate_Email           CHECK (Email IS NULL OR Email LIKE N'_%@_%._%'),
    CONSTRAINT CK_Candidate_Abn             CHECK (Abn IS NULL OR candidates.fn_IsValidAbn(Abn) = 1),
    CONSTRAINT CK_Candidate_SalaryBasis     CHECK (SalaryBasis IN (N'Daily rate', N'Hourly rate', N'Annual salary')),
    CONSTRAINT CK_Candidate_SalaryAmount    CHECK (SalaryAmount IS NULL OR SalaryAmount >= 0),
    CONSTRAINT CK_Candidate_ClearanceLevel  CHECK (ClearanceLevel IN (N'None', N'Baseline', N'NV1', N'NV2', N'PV')),
    CONSTRAINT CK_Candidate_ClearanceVerif  CHECK (ClearanceVerification IN (N'Unverified', N'Pending', N'Verified', N'Failed')),
    CONSTRAINT CK_Candidate_ClearanceExpiry CHECK (ClearanceLevel = N'None' OR ClearanceExpiry IS NOT NULL OR IsErased = 1),
    CONSTRAINT CK_Candidate_WorkRights      CHECK (WorkRights IS NULL OR WorkRights IN (N'Australian citizen', N'Permanent resident', N'NZ citizen', N'Visa holder')),
    CONSTRAINT CK_Candidate_VisaExpiry      CHECK (WorkRights IS NULL OR WorkRights <> N'Visa holder' OR VisaExpiry IS NOT NULL),
    CONSTRAINT CK_Candidate_Outreach        CHECK (LinkedInOutreachStatus IN (N'Not contacted', N'InMail sent', N'Responded', N'Interested', N'Not interested')),
    CONSTRAINT CK_Candidate_LinkedInUrl     CHECK (LinkedInUrl IS NULL OR LinkedInUrl LIKE N'http%://%linkedin.com/%'),
    CONSTRAINT CK_Candidate_ConsentMethod   CHECK (ConsentMethod IS NULL OR ConsentMethod IN (N'Email', N'Written form', N'Verbal (recorded)', N'Candidate portal')),
    CONSTRAINT CK_Candidate_Consent         CHECK (ConsentGiven = 0 OR (ConsentDate IS NOT NULL AND ConsentMethod IS NOT NULL)),
    CONSTRAINT CK_Candidate_Erased          CHECK (IsErased = 0 OR (ErasedAt IS NOT NULL AND FirstName IS NULL AND LastName IS NULL AND Email IS NULL AND Phone IS NULL))
);
GO

