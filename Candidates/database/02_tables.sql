/* ---------- ABN checksum (req 2.10). Created before the tables because a CHECK constraint uses it. ---------- */
IF OBJECT_ID(N'candidates.fn_IsValidAbn', N'FN') IS NULL
EXEC (N'
CREATE FUNCTION candidates.fn_IsValidAbn (@Abn CHAR(11))
RETURNS BIT
WITH SCHEMABINDING
AS
BEGIN
    IF @Abn IS NULL OR LEN(@Abn) <> 11 OR @Abn LIKE ''%[^0-9]%'' RETURN 0;
    DECLARE @Sum INT =
          (CAST(SUBSTRING(@Abn, 1, 1) AS INT) - 1) * 10
        + CAST(SUBSTRING(@Abn, 2, 1) AS INT) * 1
        + CAST(SUBSTRING(@Abn, 3, 1) AS INT) * 3
        + CAST(SUBSTRING(@Abn, 4, 1) AS INT) * 5
        + CAST(SUBSTRING(@Abn, 5, 1) AS INT) * 7
        + CAST(SUBSTRING(@Abn, 6, 1) AS INT) * 9
        + CAST(SUBSTRING(@Abn, 7, 1) AS INT) * 11
        + CAST(SUBSTRING(@Abn, 8, 1) AS INT) * 13
        + CAST(SUBSTRING(@Abn, 9, 1) AS INT) * 15
        + CAST(SUBSTRING(@Abn, 10, 1) AS INT) * 17
        + CAST(SUBSTRING(@Abn, 11, 1) AS INT) * 19;
    RETURN CASE WHEN @Sum % 89 = 0 THEN 1 ELSE 0 END;
END');
GO

